#!/usr/bin/env python3
"""Corbet spin-period vs orbital-period diagram for high-mass X-ray binaries.

Reads data/external/xray_binary_catalogs/corbet_hmxb.csv and writes
premium/figures/corbet.html as a standalone dashboard figure (mirroring the
plotly_dark style of the other dashboard builders). The figure content matches
the Corbet diagram embedded by the premium site.

IMPORTANT (data provenance): corbet_hmxb.csv is a SYNTHETIC demonstration
dataset — 80 seeded fake Be/XRB systems generated by
scripts/download_xray_binaries.py with published scalings as the template.
It is NOT real astronomy data and must be replaced by a genuine VizieR HMXB
catalog fetch (e.g. Corbet 1984-style classes from Liu/Corbet compilations)
before scientific use. The plot annotation states this explicitly.
"""

from pathlib import Path
import pandas as pd
import plotly.express as px

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data/external/xray_binary_catalogs/corbet_hmxb.csv"
OUT = ROOT / "premium/figures/corbet.html"

df = pd.read_csv(SRC)
fig = px.scatter(
    df,
    x="Porb_d",
    y="Pspin_s",
    color="Type",
    symbol="Type",
    log_x=True,
    log_y=True,
    hover_data={"Porb_d": ":.3f", "Pspin_s": ":.3f", "Lx_erg_s": ":.3e"},
    labels={
        "Porb_d": "Orbital period (d)",
        "Pspin_s": "Spin period (s)",
        "Type": "System type",
        "Lx_erg_s": "2–12 keV luminosity (erg/s)",
    },
    color_discrete_sequence=px.colors.qualitative.Plotly,
)
fig.update_traces(marker=dict(size=9, opacity=0.85))
fig.update_xaxes(title_text="Orbital period (days)", gridcolor="#2a3a5c")
fig.update_yaxes(title_text="Spin period (s)", gridcolor="#2a3a5c")
fig.update_layout(
    template="plotly_dark",
    height=720,
    title="Corbet diagram — HMXB spin versus orbital period",
    legend=dict(orientation="h", yanchor="bottom", y=1.0, x=0),
    annotations=[
        dict(
            text=(
                "DATA IS SYNTHETIC (test set): the plotted sample is generated "
                "by scripts/download_xray_binaries.py (80 seeded systems following "
                "Corbet-class scalings). Not real measurements; not for science use. "
                "Layout reference: Corbet et al. 1999, ApJ, 512, 339."
            ),
            xref="paper",
            yref="paper",
            x=0,
            y=-0.18,
            showarrow=False,
            align="left",
            font=dict(size=11, color="#c33"),
        )
    ],
    margin=dict(b=110),
)
OUT.parent.mkdir(parents=True, exist_ok=True)
fig.write_html(OUT, include_plotlyjs="cdn")
print(f"{OUT}; plotted {len(df)} synthetic HMXB demo points")
