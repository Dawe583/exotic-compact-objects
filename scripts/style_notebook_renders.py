#!/usr/bin/env python3
"""
Apply the Astro Science dark theme and navigation bar to nbconvert HTML renders
in docs/.

The notebook HTML files are generated by nbconvert and are not edited by hand.
This script injects a stylesheet link and a small navigation shell into each
render. It is idempotent: blocks are wrapped in markers and replaced on every
run, so it can be called after any re-render.

Usage:
    python scripts/style_notebook_renders.py
"""

from __future__ import annotations

import html
import re
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
DOCS = PROJECT / "docs"
GITHUB = "https://github.com/Dawe583/exotic-compact-objects"

START = "<!-- asp-nb:start -->"
END = "<!-- asp-nb:end -->"

BRAND_SVG = (
    '<svg viewBox="0 0 24 24" fill="none" stroke="#58d3ff" stroke-width="1.6" '
    'aria-hidden="true"><circle cx="12" cy="12" r="3.2" fill="#58d3ff" '
    'stroke="none"/><ellipse cx="12" cy="12" rx="9.5" ry="4.2" '
    'transform="rotate(-24 12 12)"/><ellipse cx="12" cy="12" rx="9.5" ry="4.2" '
    'transform="rotate(36 12 12)" opacity=".55"/></svg>'
)


def humanize(stem: str) -> str:
    return stem.replace("_", " ").strip().capitalize()


def strip_old_blocks(text: str) -> str:
    # Remove the block together with the newline that precedes it so that a
    # repeated run produces byte-identical output.
    return re.sub(
        r"\n?" + re.escape(START) + r".*?" + re.escape(END),
        "",
        text,
        flags=re.S,
    )


def build_bar(title: str) -> str:
    return f"""{START}
<link rel="stylesheet" href="notebook.css">
<div class="asp-nb-bar">
  <a class="asp-brand" href="index.html">{BRAND_SVG}<span>Astro Science</span></a>
  <span class="asp-title">{html.escape(title)}</span>
  <span class="asp-links">
    <a href="index.html">All notebooks</a>
    <a href="premium/index.html">Research site</a>
    <a class="primary" href="{GITHUB}">GitHub</a>
  </span>
</div>
{END}"""


def build_footer() -> str:
    return f"""{START}
<div class="asp-nb-foot">
  <span>Astro Science · notebook render</span>
  <span><a href="index.html">← All notebooks</a> · <a href="premium/theory.html">Theory</a> · <a href="premium/data.html">Data</a></span>
</div>
{END}"""


def process(path: Path) -> bool:
    text = path.read_text(encoding="utf-8", errors="replace")
    if "<body" not in text or "<html" not in text:
        return False

    title_match = re.search(r"<title>(.*?)</title>", text, re.S | re.I)
    title = (
        html.unescape(title_match.group(1)).strip()
        if title_match
        else humanize(path.stem)
    )
    title = title.replace("_", " ").strip()

    original = text
    text = strip_old_blocks(text)

    # stylesheet + bar right after <body ...>
    if "notebook.css" not in text:
        bar = build_bar(title)
        text = re.sub(
            r"(<body[^>]*>)",
            lambda m: m.group(1) + "\n" + bar,
            text,
            count=1,
            flags=re.I,
        )
    else:
        # bar block was stripped together with the stylesheet; re-inject
        bar = build_bar(title)
        text = re.sub(
            r"(<body[^>]*>)",
            lambda m: m.group(1) + "\n" + bar,
            text,
            count=1,
            flags=re.I,
        )

    # footer before </body>
    text = re.sub(
        r"</body>",
        build_footer() + "\n</body>",
        text,
        count=1,
        flags=re.I,
    )

    if text != original:
        path.write_text(text, encoding="utf-8")
        return True
    return False


def main() -> None:
    changed = []
    for path in sorted(DOCS.glob("*.html")):
        if path.name == "index.html":
            continue
        if process(path):
            changed.append(path.name)
    print(f"Styled {len(changed)} notebook renders.")
    for name in changed:
        print(f"  • {name}")


if __name__ == "__main__":
    main()
